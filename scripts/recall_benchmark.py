#!/usr/bin/env python3
"""NFR-003 / ADR-0011 A3 recall benchmark for `mcp-pgvector` (T-066).

Recall@k of the server's HNSW search against exact brute force (`enable_indexscan = off`) over a set
of queries (`eval/recall_queries.yaml`, 50 queries). Passing bar: mean recall >= 0.95.

    # reproducible synthetic run with the deterministic fake provider (what the test suite does)
    uv run python scripts/recall_benchmark.py --dsn postgresql://postgres@localhost/mcp_kb \
        --load-synthetic --provider fake
    # real run, once the corpus was ingested with the real model (spike S2 decision)
    uv run python scripts/recall_benchmark.py --dsn <mcp_query_ro DSN> --provider configured \
        --queries eval/my_real_queries.yaml

The synthetic corpus is generated here and loaded THROUGH the ingest pipeline (T-075), so the
benchmark also exercises persist. With the fake provider the numbers say nothing about semantic
quality, only about the index: a real-model run is still pending (docs/signoff/phase-3.md).

Read-only against the target except `--load-synthetic`, which writes through the pipeline and needs
the `mcp_ingest_rw` (or admin) DSN.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import random
import sys
from collections.abc import Iterable, Iterator
from dataclasses import dataclass
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Any

import psycopg
import yaml

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_QUERIES = ROOT / "eval" / "recall_queries.yaml"
THRESHOLD = 0.95  # NFR-003 / ADR-0011 A3 (the value is not a PO-owned open question)
TOPICS = 60
WORDS_PER_TOPIC = 8
FILLER = [f"common{i}" for i in range(120)]
T0 = datetime(2026, 9, 1, tzinfo=UTC)


def topic_word(topic: int, j: int) -> str:
    return f"topic{topic}w{j}"


def synthetic_documents(seed: int = 7, per_topic: int = 22) -> Iterator[tuple[str, int, str]]:
    """(source_id, topic, html) — two short paragraphs per document, topic words + filler."""
    rng = random.Random(seed)
    n = 0
    for topic in range(TOPICS):
        for _ in range(per_topic):
            paragraphs = []
            for _p in range(2):
                words = [topic_word(topic, rng.randrange(WORDS_PER_TOPIC)) for _ in range(6)]
                words += rng.sample(FILLER, 24)
                rng.shuffle(words)
                paragraphs.append("<p>" + " ".join(words) + "</p>")
            n += 1
            yield str(1000 + n), topic, f"<h1>Topic {topic} note {n}</h1>" + "".join(paragraphs)


def synthetic_queries(seed: int = 7, count: int = 50) -> list[dict[str, Any]]:
    rng = random.Random(seed + 1)
    queries = []
    for i in range(count):
        topic = (i * 7) % TOPICS
        words = [topic_word(topic, j) for j in rng.sample(range(WORDS_PER_TOPIC), 3)]
        words += rng.sample(FILLER, 2)
        rng.shuffle(words)
        queries.append({"id": f"RQ-{i + 1:03d}", "topic": topic, "text": " ".join(words)})
    return queries


def write_queries(path: Path = DEFAULT_QUERIES) -> None:
    header = (
        "# Recall benchmark queries (T-066, NFR-003, ADR-0011 A3). SYNTHETIC: generated by\n"
        "# `scripts/recall_benchmark.py --write-queries` (seed 7) over the synthetic corpus of the\n"  # noqa: E501
        "# same script; regenerate instead of editing. For a real-model run replace them with\n"
        "# queries taken from eval/questions.yaml phrased against the real corpus.\n"
        "# Fields: id, topic (synthetic topic id; informational), text.\n"
    )
    body = yaml.safe_dump({"version": 1, "synthetic": True, "queries": synthetic_queries()},
                          sort_keys=False, allow_unicode=True)  # fmt: skip
    path.write_text(header + body, encoding="utf-8")


def load_queries(path: Path = DEFAULT_QUERIES) -> list[dict[str, Any]]:
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    queries = list(data["queries"])
    ids = [q["id"] for q in queries]
    if len(set(ids)) != len(ids) or any(not q.get("text") for q in queries):
        raise ValueError(f"{path}: query ids must be unique and every query needs text")
    return queries


@dataclass
class RecallReport:
    top_k: int
    per_query: dict[str, float]
    index_used: bool

    @property
    def mean(self) -> float:
        return sum(self.per_query.values()) / len(self.per_query) if self.per_query else 0.0

    @property
    def minimum(self) -> float:
        return min(self.per_query.values(), default=0.0)

    def as_dict(self) -> dict[str, Any]:
        return {
            "top_k": self.top_k, "queries": len(self.per_query), "mean_recall": round(self.mean, 4),
            "min_recall": round(self.minimum, 4), "hnsw_index_used": self.index_used,
            "threshold": THRESHOLD, "passed": self.mean >= THRESHOLD and self.index_used,
        }  # fmt: skip


def _vector(values: Iterable[float]) -> str:
    return "[" + ",".join(repr(float(v)) for v in values) + "]"


_BRUTE = """
SELECT c.id FROM kb.chunks c JOIN kb.documents d ON d.id = c.document_id
WHERE d.deleted_at IS NULL AND c.embedding_model = %(model)s
ORDER BY c.embedding <=> %(q)s::vector LIMIT %(k)s
"""


def brute_force_ids(conn: psycopg.Connection, vector: list[float], model: str, k: int) -> list[int]:
    """Exact top-k: the planner may not use the index (`enable_indexscan = off`)."""
    with conn.transaction():
        conn.execute("SET LOCAL enable_indexscan = off")
        conn.execute("SET LOCAL enable_bitmapscan = off")
        rows = conn.execute(_BRUTE, {"model": model, "q": _vector(vector), "k": k}).fetchall()
    return [r[0] for r in rows]


def force_index_dsn(dsn: str) -> str:
    """The same DSN with `enable_seqscan = off` for the session.

    At production size the planner always picks the HNSW index; on a small benchmark corpus it
    would pick a sequential scan, which is exact and would make recall trivially 1.0. Forcing the
    index makes the benchmark measure the index. Never use this DSN for serving.
    """
    separator = "&" if "?" in dsn else "?"
    return f"{dsn}{separator}options=-c%20enable_seqscan%3Doff"


def index_is_used(conn: psycopg.Connection, vector: list[float], model: str, k: int) -> bool:
    """True when the server's `search` statement plans an HNSW index scan in this session."""
    from mcp_pgvector.sql import STATEMENTS

    params = {
        "model": model, "query": _vector(vector), "limit": k * 4, "source_types": [],
        "container": None, "updated_after": None,
    }  # fmt: skip
    plan = conn.execute("EXPLAIN " + STATEMENTS["search"], params).fetchall()
    return any("chunks_embedding_hnsw" in row[0] for row in plan)


async def measure(
    dsn: str, provider: Any, queries: list[dict[str, Any]], *, top_k: int = 10
) -> RecallReport:
    """Recall of `PgVectorReadApi.semantic_search` (the real server code path) vs brute force."""
    from mcp_common.config import CommonSettings
    from mcp_pgvector.client import PgVectorClient
    from mcp_pgvector.read_api import PgVectorReadApi
    from mcp_pgvector.settings import Settings
    from pydantic import SecretStr

    ann_dsn = force_index_dsn(dsn)
    settings = Settings(dsn=SecretStr(ann_dsn))
    client = PgVectorClient(settings, common=CommonSettings())
    api = PgVectorReadApi(client, provider, CommonSettings(), settings,
                          now=lambda: datetime.now(UTC))  # fmt: skip
    per_query: dict[str, float] = {}
    try:
        with psycopg.connect(dsn, autocommit=True) as conn:
            probe = provider.embed_query(queries[0]["text"])
            with psycopg.connect(ann_dsn, autocommit=True) as probe_conn:
                used = index_is_used(probe_conn, probe, provider.model_id, top_k)
            for query in queries:
                vector = provider.embed_query(query["text"])
                exact = set(brute_force_ids(conn, vector, provider.model_id, top_k))
                outcome = await api.semantic_search(
                    query=query["text"], top_k=top_k, min_similarity=0.0
                )
                approx = {int(item["chunk_id"]) for item in outcome.result.items}  # ids are strings
                per_query[query["id"]] = len(exact & approx) / max(len(exact), 1)
    finally:
        await client.aclose()
    return RecallReport(top_k, per_query, used)


class SyntheticConnector:
    """A `SourceConnector` over the synthetic corpus (loaded through the real pipeline)."""

    source_type = "confluence"
    name = "SyntheticConnector"
    operations_used: tuple[str, ...] = ()

    def __init__(self, per_topic: int = 22) -> None:
        self._per_topic = per_topic

    def status(self) -> Any:
        from mcp_ingest.connectors.base import ConnectorStatus

        return ConnectorStatus(enabled=True, configured=True)

    def iter_documents(self, cursor: Any, mode: str, *, limit: int | None = None) -> Iterator[Any]:
        from mcp_ingest.connectors.base import SourceDocument

        for index, (source_id, topic, html) in enumerate(
            synthetic_documents(per_topic=self._per_topic)
        ):
            yield SourceDocument(
                source_type="confluence", source_id=source_id,
                source_uri=f"https://wiki.example.com/pages/viewpage.action?pageId={source_id}",
                raw_content=html, source_format="html",
                source_updated_at=T0 + timedelta(minutes=index), title=f"Topic {topic}",
                container="SYN", visibility="team",
            )  # fmt: skip

    def fetch_documents(self, source_ids: Iterable[str]) -> Iterator[Any]:
        return iter(())

    def close(self) -> None:
        return None


def load_synthetic(rw_dsn: str, provider: Any, per_topic: int = 22) -> int:
    """Ingest the synthetic corpus via the pipeline; returns the number of chunks written."""
    from mcp_ingest.pipeline.chunk import ChunkConfig
    from mcp_ingest.pipeline.run import RunContext, RunOptions, run_ingest

    ctx = RunContext(dsn=rw_dsn, provider=provider, chunk_config=ChunkConfig(64, 8), deny_globs=[],
                     batch_size=64)  # fmt: skip
    connector = SyntheticConnector(per_topic)
    report = run_ingest(
        ctx, RunOptions(sources=["confluence"]),
        describe=lambda _n: connector.status(), build=lambda _n: connector, explicit_source=False,
    )  # fmt: skip
    # NOTE: `ANALYZE` needs table ownership, which `mcp_ingest_rw` does not have (autovacuum does it
    # in production); run it as the owner before measuring so the planner has real statistics.
    return report.sources[0].chunks_written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter
    )
    parser.add_argument("--dsn", help="database DSN (mcp_query_ro for measuring)")
    parser.add_argument("--queries", type=Path, default=DEFAULT_QUERIES)
    parser.add_argument("--top-k", type=int, default=10)
    parser.add_argument("--provider", choices=["fake", "configured"], default="fake")
    parser.add_argument(
        "--load-synthetic", action="store_true", help="ingest the synthetic corpus first"
    )
    parser.add_argument(
        "--write-queries", action="store_true", help="(re)generate the queries file"
    )
    args = parser.parse_args(argv)

    if args.write_queries:
        write_queries(args.queries)
        print(f"wrote {args.queries}")
        return 0
    if not args.dsn:
        parser.error("--dsn is required")
    if args.provider == "fake":
        from mcp_ingest.embedding.fake import DeterministicFakeProvider

        provider: Any = DeterministicFakeProvider()
    else:
        from mcp_ingest.embedding import EmbeddingSettings, build_provider

        provider = build_provider(EmbeddingSettings())
    if args.load_synthetic:
        print(f"loaded {load_synthetic(args.dsn, provider)} chunks", file=sys.stderr)
    report = asyncio.run(measure(args.dsn, provider, load_queries(args.queries), top_k=args.top_k))
    print(json.dumps(report.as_dict(), indent=2))
    return 0 if report.as_dict()["passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
